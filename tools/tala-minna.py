def norm(s):
    s = re.sub(r"[ً-ْٰـ]", "", s)
    s = re.sub(r"\(\s*[\d٠-٩]+\s*\)", "", s)
    return re.sub(r"\s+", " ", s).strip()


def main():
    pages = json.load(open(os.path.join(ROOT, "data", "books", BID + ".json"), encoding="utf-8"))["pages"]
    bad = 0
    for k, units in U.items():
        for u in units:
            u["b"] = BID
            for l in u["ls"]:
                for p, t in l["pts"]:
                    if norm(t) not in norm(pages[p - 1]):
                        print("غير موجود في صفحته:", k, p, t[:60]); bad += 1
                for q in l["q"]:
                    assert len(q) == 4 and len(set(q[1:])) == 3, q
    if bad:
        sys.exit(1)
    mp = os.path.join(ROOT, "data", "tala-manhaj.json")
    M = json.load(open(mp, encoding="utf-8"))
    M["units"] = U
    json.dump(M, open(mp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("وحدات:", {k: sum(len(u["ls"]) for u in v) for k, v in U.items()})


