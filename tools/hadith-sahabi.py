#!/usr/bin/env python3
"""مسند كل صحابي من بيانات كتب السنة المعروضة في المكتبة (data/hadith/k/*.json).
يحسب العدد الحقيقي للأحاديث المنسوبة لكل صحابي في المسند المعروض، بدل الأرقام الثابتة، ويكتب:
  data/hadith/sahabi/_index.json  ← [[الاسم، العدد، عدد الكتب]] مرتبة بالعدد
  data/hadith/sahabi/<n>.json     ← [[الكتاب، الرقم]] لأحاديثه (مرتبة بأولوية الكتب)
الحقل «الصحابي» في البيانات مستخرج من الإسناد وقد يحمل غير الصحابي (تابعيًّا أو ضميرًا)؛ فيُحصى هنا الصحابة المعروفون وحدهم
(قائمة ALIAS) بأسمائهم المتعددة (ابن عمر = عبد الله بن عمر ...) ويُترك الاسم المبهم («عبد الله»، «أبيه»، «النبي»...).
يُشغَّل بعد أي تحديث لبيانات الأحاديث: python3 tools/hadith-sahabi.py"""
import json, glob, re, os, collections
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "hadith")
def nk(s):
    s = re.sub(r"[\u064b-\u065f\u0670\u0640]", "", s); s = re.sub(r"[أإآٱ]", "ا", s).replace("ى", "ي").replace("ة", "ه")
    s = re.sub(r"امير المومنين|رضي الله (عنه|عنها|عنهما|عنهم)", "", s); s = re.sub(r"^(ابي|ابا)\b", "ابو", s.strip())
    return re.sub(r"\s+", " ", s).strip()
ALIAS = {
 "أبو هريرة": ["ابو هريره"], "عائشة أم المؤمنين": ["عائشه"], "عبد الله بن عباس": ["ابن عباس", "عبد الله بن عباس"],
 "عبد الله بن عمر": ["ابن عمر", "عبد الله بن عمر"], "أنس بن مالك": ["انس", "انس بن مالك"], "جابر بن عبد الله": ["جابر", "جابر بن عبد الله"],
 "أبو سعيد الخدري": ["ابو سعيد", "ابو سعيد الخدري"], "علي بن أبي طالب": ["علي", "علي بن ابي", "علي بن ابي طالب"], "أم سلمة": ["ام سلمه"],
 "أبو موسى الأشعري": ["ابو موسي", "ابو موسي الاشعري"], "عبد الله بن مسعود": ["ابن مسعود", "عبد الله بن مسعود"],
 "عبد الله بن عمرو بن العاص": ["عبد الله بن عمرو", "ابن عمرو"], "أبو أمامة الباهلي": ["ابو امامه"], "أبو ذر الغفاري": ["ابو ذر"],
 "عمران بن حصين": ["عمران بن حصين"], "عمر بن الخطاب": ["عمر", "عمر بن الخطاب"], "حذيفة بن اليمان": ["حذيفه"], "سهل بن سعد": ["سهل بن سعد"],
 "جابر بن سمرة": ["جابر بن سمره"], "عقبة بن عامر": ["عقبه بن عامر"], "معاذ بن جبل": ["معاذ بن جبل"], "البراء بن عازب": ["البراء بن عازب", "البراء"],
 "زيد بن ثابت": ["زيد بن ثابت"], "أبو الدرداء": ["ابو الدرداء"], "أبو مسعود الأنصاري": ["ابو مسعود"], "أبو أيوب الأنصاري": ["ابو ايوب"],
 "سمرة بن جندب": ["سمره بن جندب", "سمره"], "عبادة بن الصامت": ["عباده بن الصامت"], "المغيرة بن شعبة": ["المغيره بن شعبه"],
 "النعمان بن بشير": ["النعمان بن بشير"], "جرير بن عبد الله": ["جرير"], "أبو بكر الصديق": ["ابو بكر", "ابو بكر الصديق"],
 "عثمان بن عفان": ["عثمان", "عثمان بن عفان"], "أبو قتادة": ["ابو قتاده"], "أبو بكرة": ["ابو بكره"], "عمرو بن العاص": ["عمرو بن العاص"],
 "عبد الله بن الزبير": ["ابن الزبير", "عبد الله بن الزبير"], "ثوبان": ["ثوبان"], "أبو رافع": ["ابو رافع"], "أسماء بنت أبي بكر": ["اسماء بنت ابو بكر"],
 "أبو الطفيل": ["ابو الطفيل"], "بريدة بن الحصيب": ["بريده", "بريده بن الحصيب"], "عدي بن حاتم": ["عدي بن حاتم"], "أبو حميد الساعدي": ["ابو حميد"],
 "معاوية بن أبي سفيان": ["معاويه", "معاويه بن ابو سفيان"], "كعب بن مالك": ["كعب بن مالك"], "أبي بن كعب": ["ابي بن كعب"], "سلمان الفارسي": ["سلمان"],
 "عوف بن مالك": ["عوف بن مالك"], "وائل بن حجر": ["وائل بن حجر"], "فاطمة بنت قيس": ["فاطمه بنت قيس"], "ميمونة": ["ميمونه"], "حفصة": ["حفصه"], "أم حبيبة": ["ام حبيبه"],
}
LOOK = {k: n for n, ks in ALIAS.items() for k in ks}
PRI = ["bukhari", "muslim", "muwatta", "abudawud", "tirmidhi", "nasai", "ibnmajah", "darimi", "musnadahmad"]
pr = lambda b: PRI.index(b) if b in PRI else 99
D = collections.defaultdict(list)
for f in sorted(glob.glob(os.path.join(R, "k", "*.json"))):
    if os.path.basename(f).startswith("_"): continue
    try: d = json.load(open(f, encoding="utf8"))
    except Exception: continue
    fb = os.path.basename(f)[:-5]
    for x in (d.get("items") if isinstance(d, dict) else None) or []:
        n = LOOK.get(nk(x[5] or "")) if len(x) > 5 else None
        if n: D[n].append((fb, x[0]))
os.makedirs(os.path.join(R, "sahabi"), exist_ok=True)
for o in glob.glob(os.path.join(R, "sahabi", "*.json")): os.remove(o)
idx = []
for i, (n, L) in enumerate(sorted(D.items(), key=lambda z: -len(z[1]))):
    L.sort(key=lambda z: pr(z[0]))
    idx.append([n, len(L), len({b for b, _ in L})])
    json.dump(L, open(os.path.join(R, "sahabi", f"{i}.json"), "w"), ensure_ascii=False, separators=(",", ":"))
json.dump(idx, open(os.path.join(R, "sahabi", "_index.json"), "w"), ensure_ascii=False, separators=(",", ":"))
print(len(idx), "صحابيًّا؛ مجموع المنسوب", sum(c for _, c, _ in idx)); print(idx[:6])
