RX = [(t, re.compile(r)) for t, r in TOPICS]
def topic(kitab, bab):
    for src in (kitab, bab):
        if not src: continue
        s = re.sub(r"^(?:[\d٠-٩]+\s*[-–]\s*)?", "", src)
        for i, (t, rx) in enumerate(RX):
            # «الإيمان» (العقيدة) غير «الأيمان» (اليمين): يُفرَّق بالهمزة
            if i == 0 and re.search(r"الأيمان", s) and not re.search(r"الإيمان", s): continue
            if rx.search(s): return i
    return len(RX)
def main():
    os.makedirs(OUT, exist_ok=True)
    groups = {}  # topic -> {(src,kitab,bab): [ids]}
    names = {}
    for f in sorted(glob.glob(os.path.join(H, "k", "*.json"))):
        bid = os.path.basename(f)[:-5]
        if bid.startswith("_"): continue
        d = json.load(open(f, encoding="utf-8")); names[bid] = d.get("t", bid)
        for x in d["items"]:
            i = topic(x[3], x[4]); groups.setdefault(i, {}).setdefault((bid, x[3] or "", x[4] or ""), []).append(x[0])
    try:
        ix = json.load(open(os.path.join(H, "index.json"), encoding="utf-8")); names.update(ix.get("books", {}))
        for r in ix["items"]:
            if r[1] == "arbain": continue
            i = topic(r[3], r[4])
            if i == len(RX) and r[1] == "riyad": i = [t for t, _ in TOPICS].index("الرقاق والزهد والتوبة")  # أبواب رياض الصالحين الأولى: أعمال القلوب والرقائق
            groups.setdefault(i, {}).setdefault((r[1], r[3] or "", r[4] or ""), []).append(r[0])
    except Exception as e: print("الكتب المختارة:", e)
    idx = []
    allT = [t for t, _ in TOPICS] + ["أبواب متفرقة"]
    for i, t in enumerate(allT):
        g = groups.get(i, {}); n = sum(len(v) for v in g.values())
        idx.append([t, n, len(g)])
        json.dump({"t": t, "a": [[b, src, k, ids] for (src, k, b), ids in g.items()], "books": names}, open(os.path.join(OUT, "%d.json" % i), "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    json.dump(idx, open(os.path.join(OUT, "_index.json"), "w", encoding="utf-8"), ensure_ascii=False)
    for t, n, a in idx: print(t, n, a)
if __name__ == "__main__":
    main()
